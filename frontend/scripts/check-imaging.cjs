// End-to-end check against a locally running prepared case. No dataset is committed.
const { chromium } = require('@playwright/test');
const path = require('node:path');
const fs = require('node:fs');

(async () => {
  const executablePath = process.env.CHROME_PATH;
  const browser = await chromium.launch({ headless: true, ...(executablePath ? { executablePath } : {}),
    args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const context = await browser.newContext({ viewport: { width: 1500, height: 1050 }, deviceScaleFactor: 1 });
  const page = await context.newPage();
  const failures = [];
  page.on('pageerror', e => failures.push(e.message));
  const base = process.env.IMAGING_BASE_URL || 'http://127.0.0.1:8001';
  const login = await context.request.post(`${base}/api/auth/demo-enter`, { data: { username: 'dr.layla' } });
  if (!login.ok()) throw new Error(`Sign-in failed: ${login.status()} ${await login.text()}`);
  await page.goto(base);
  await page.getByRole('button', { name: /Brain Analytics|تحليل صور الدماغ/ }).click();
  await page.getByRole('button', { name: 'Images & 3D', exact: true }).click();
  await page.getByText('OAS1_0001_MR1', { exact: true }).waitFor({ timeout: 90000 });
  await page.getByLabel('Interactive scan-derived 3D brain').locator('canvas').waitFor();
  await page.waitForTimeout(1800);
  if (await page.getByRole('alert').count()) throw new Error(await page.getByRole('alert').allTextContents());
  const output = path.resolve(__dirname, '../../backend/imaging_data/verification'); fs.mkdirSync(output, { recursive: true });
  await page.screenshot({ path: path.join(output, 'brain-workspace.png'), fullPage: true });
  const brainCanvas = page.getByLabel('Interactive scan-derived 3D brain').locator('canvas');
  const box = await brainCanvas.boundingBox();
  await brainCanvas.click({ position: { x: box.width / 2, y: box.height / 2 } });
  await page.getByRole('button', { name: 'Clear selection', exact: true }).waitFor();
  await page.getByLabel('Surface', { exact: true }).selectOption('white');
  await page.getByLabel('Surface colors').selectOption('thickness');
  await page.getByLabel('Zoom brain in').click();
  await page.getByLabel('Zoom brain out').click();
  await page.getByLabel('Segmentation overlay').check();
  await page.getByLabel('Sagittal slice', { exact: true }).fill('115');
  await page.getByLabel('Axial MRI view', { exact: true }).locator('canvas').click({ position: { x: 100, y: 90 } });
  await page.getByRole('button', { name: 'Explore inside', exact: true }).click();
  await page.getByText('Inside exploration', { exact: true }).waitFor();
  if (!await page.getByLabel('MRI cutting planes', { exact: true }).isChecked()) throw new Error('Inside mode has no MRI planes.');
  await page.waitForTimeout(1000);
  await page.screenshot({ path: path.join(output, 'brain-inside.png'), fullPage: true });
  await page.getByRole('button', { name: 'Reset', exact: true }).click();
  await page.getByLabel('Surface', { exact: true }).selectOption('inflated');
  if (!await page.getByLabel('MRI cutting planes', { exact: true }).isDisabled()) throw new Error('Inflated geometry should not show aligned MRI planes.');
  await page.getByRole('button', { name: 'Measurements', exact: true }).click();
  const count = await page.locator('tbody tr').count();
  if (count !== 118) throw new Error(`Expected 118 statistics rows, got ${count}`);
  await page.getByLabel('Filter measurements').fill('hippocampus');
  if (await page.locator('tbody tr').count() !== 2) throw new Error('Hippocampal statistics missing.');
  await page.locator('tbody button').first().click();
  await page.getByRole('heading', { name: 'Left-Hippocampus', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Source & quality', exact: true }).click();
  await page.getByText('freesurfer-Linux-centos4-dev-20061005', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Images & 3D', exact: true }).click();
  await page.setViewportSize({ width: 820, height: 1100 });
  await page.screenshot({ path: path.join(output, 'brain-narrow.png'), fullPage: true });
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 2);
  if (overflow) throw new Error('Workspace overflows narrow viewport.');
  await page.setViewportSize({ width: 420, height: 900 });
  await page.screenshot({ path: path.join(output, 'brain-mobile.png'), fullPage: true });
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 2)) throw new Error('Workspace overflows phone viewport.');
  await page.getByRole('button', { name: 'Clinical workspace', exact: true }).click();
  await page.getByRole('button', { name: /Brain Analytics|تحليل صور الدماغ/ }).waitFor();
  if (failures.length) throw new Error(failures.join('\n'));
  console.log(JSON.stringify({ status: 'passed', rows: count, browserErrors: failures, screenshots: output }));
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
