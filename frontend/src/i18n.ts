export const dict = { en, ar };

export type T = ((key: Key, vars?: Record<string, string | number>) => string) & {
  lang: Lang;
  code: (c: string | null | undefined) => string;
  date: (iso: string | null | undefined, withTime?: boolean) => string;
  num: (n: number, digits?: number) => string;
};

export function makeT(lang: Lang): T {
  const table = dict[lang];
  const fn = ((key: Key, vars?: Record<string, string | number>) => {
    let s = table[key] ?? en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  }) as T;
  const locale = lang === "ar" ? "ar-AE" : "en-GB";
  fn.lang = lang;
  fn.code = (c) => (c ? codes[lang][c] ?? codes.en[c] ?? c : "");
  fn.date = (iso, withTime = false) => {
    if (!iso) return "";
    const d = new Date(iso);
    return new Intl.DateTimeFormat(locale, withTime
      ? { day: "numeric", month: "short", year: "numeric", hour: "2-digit", minute: "2-digit" }
      : { day: "numeric", month: "short", year: "numeric" }).format(d);
  };
  fn.num = (n, digits = 0) => new Intl.NumberFormat(locale, { maximumFractionDigits: digits }).format(n);
  return fn;
}

export const LangContext = createContext<{ t: T; setLang: (l: Lang) => void }>({
  t: makeT("en"), setLang: () => undefined,
});

export const useT = () => useContext(LangContext);
